namespace Anvil.API
{
  /// <summary>
  /// Common style constants for standard NUI control dimensions.
  /// </summary>
  public static class NuiStyle
  {
    /// <summary>
    /// Default height for primary controls.
    /// </summary>
    public const float PrimaryHeight = 50.0f;

    /// <summary>
    /// Default width for primary controls.
    /// </summary>
    public const float PrimaryWidth = 150.0f;

    /// <summary>
    /// Default row height for list/grid items.
    /// </summary>
    public const float RowHeight = 25.0f;

    /// <summary>
    /// Default height for secondary controls.
    /// </summary>
    public const float SecondaryHeight = 35.0f;

    /// <summary>
    /// Default width for secondary controls.
    /// </summary>
    public const float SecondaryWidth = 150.0f;

    /// <summary>
    /// Default height for tertiary controls.
    /// </summary>
    public const float TertiaryHeight = 30.0f;

    /// <summary>
    /// Default width for tertiary controls.
    /// </summary>
    public const float TertiaryWidth = 100.0f;
  }
}
